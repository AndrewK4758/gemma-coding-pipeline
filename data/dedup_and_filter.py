#!/usr/bin/env python3
"""Three-stage dataset quality filtering and deduplication pipeline.

Stage A : Heuristic Quality Filter (auto-generated headers, minified lines >500 chars, empty/tiny code blocks)
Stage B : Lexical Near-Duplicate Removal via datasketch MinHash LSH (5-gram token shingling, threshold=0.85, num_perm=128)
Stage C : Semantic Embedding Deduplication via local CPU nomic-embed-text (:11434/v1/embeddings, cosine > 0.94)
"""

from __future__ import annotations

import json
import re
import urllib.request
from typing import Any

import torch
from datasketch import MinHash, MinHashLSH

from data.ingest_sources import extract_fenced_code

AUTOGEN_MARKERS = (
    "<auto-generated",
    "do not edit",
    "code generated by",
    "@generated",
    "autogenerated",
    "this file was automatically generated",
)
TOKEN_RE = re.compile(r"[A-Za-z0-9_]+|[^\sA-Za-z0-9_]")
STEP_COMMENT_RE = re.compile(r"\s*//\s*step-\d+\b")


def passes_heuristic_filter(record: dict[str, Any], max_line_len: int = 500, min_code_lines: int = 4) -> bool:
    """Stage A: Drop auto-generated files, minified lines (>500 chars), boilerplate, or empty code blocks."""
    instruction = str(record.get("instruction", "")).strip()
    response = str(record.get("response", "")).strip()
    if len(instruction) < 15 or len(response) < 35:
        return False

    code = extract_fenced_code(response)
    if not code:
        return False

    lower_head = code[:600].lower()
    if any(marker in lower_head for marker in AUTOGEN_MARKERS):
        return False

    lines = code.splitlines()
    non_empty_lines = [ln for ln in lines if ln.strip()]
    if len(non_empty_lines) < min_code_lines:
        return False

    if any(len(ln) > max_line_len for ln in lines):
        return False

    return True


def _extract_5gram_shingles(text: str, n: int = 5) -> set[bytes]:
    """Tokenize text into lexical tokens and construct n-gram byte shingles."""
    tokens = TOKEN_RE.findall(text)
    if len(tokens) < n:
        return {" ".join(tokens).encode("utf-8")} if tokens else {b""}
    return {" ".join(tokens[i : i + n]).encode("utf-8") for i in range(len(tokens) - n + 1)}


def _compute_minhash(shingles: set[bytes], num_perm: int = 128) -> MinHash:
    mh = MinHash(num_perm=num_perm)
    for shingle in shingles:
        mh.update(shingle)
    return mh


def deduplicate_minhash_lsh(
    records: list[dict[str, Any]],
    threshold: float = 0.85,
    num_perm: int = 128,
) -> tuple[list[dict[str, Any]], int]:
    """Stage B: Remove lexical near-duplicates in O(N) using 5-gram shingling + MinHash LSH."""
    lsh = MinHashLSH(threshold=threshold, num_perm=num_perm)
    kept: list[dict[str, Any]] = []
    dropped = 0

    for idx, rec in enumerate(records):
        code_and_prompt = f"{rec['instruction']}\n{rec['response']}"
        shingles = _extract_5gram_shingles(code_and_prompt, n=5)
        mh = _compute_minhash(shingles, num_perm=num_perm)
        matches = lsh.query(mh)
        if matches:
            dropped += 1
            continue
        key = f"doc_{idx}_{rec['id']}"
        lsh.insert(key, mh)
        kept.append(rec)

    return kept, dropped


def _fetch_embeddings_batch(
    texts: list[str],
    endpoint: str = "http://127.0.0.1:11434/v1/embeddings",
    model: str = "embedding",
) -> list[list[float]]:
    """Call local CPU nomic-embed-text endpoint on :11434 (0 MB GPU VRAM on Ryzen 9 9955HX3D)."""
    payload = json.dumps({"model": model, "input": texts}).encode("utf-8")
    req = urllib.request.Request(
        endpoint,
        data=payload,
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    with urllib.request.urlopen(req, timeout=60) as resp:
        body = json.loads(resp.read().decode("utf-8"))
    data = sorted(body.get("data", []), key=lambda item: item.get("index", 0))
    return [item["embedding"] for item in data]


def deduplicate_semantic_embeddings(
    records: list[dict[str, Any]],
    cosine_threshold: float = 0.94,
    batch_size: int = 32,
    endpoint: str = "http://127.0.0.1:11434/v1/embeddings",
) -> tuple[list[dict[str, Any]], int, float]:
    """Stage C: Compute nomic-embed-text embeddings on CPU and drop pairs with cosine similarity > 0.94."""
    if not records:
        return [], 0, 0.0

    embed_inputs: list[str] = []
    for rec in records:
        cleaned_resp = STEP_COMMENT_RE.sub("", rec["response"])
        code = extract_fenced_code(cleaned_resp) or cleaned_resp
        snippet = f"Language: {rec['language']}\nTask: {rec['instruction'][:500]}\nCode:\n{code[:1100]}"
        embed_inputs.append(snippet)

    all_vectors: list[list[float]] = []
    for start in range(0, len(embed_inputs), batch_size):
        batch = embed_inputs[start : start + batch_size]
        all_vectors.extend(_fetch_embeddings_batch(batch, endpoint=endpoint))

    # L2-normalize embedding matrix on CPU using torch (float32)
    mat = torch.tensor(all_vectors, dtype=torch.float32)
    norms = torch.norm(mat, p=2, dim=1, keepdim=True).clamp(min=1e-12)
    mat_norm = mat / norms

    kept_indices: list[int] = []
    dropped = 0
    max_cosine_seen = 0.0

    for i in range(len(records)):
        if not kept_indices:
            kept_indices.append(i)
            continue
        kept_mat = mat_norm[kept_indices]
        sims = torch.mv(kept_mat, mat_norm[i])
        max_sim = float(sims.max().item())
        if max_sim > max_cosine_seen:
            max_cosine_seen = max_sim
        if max_sim > cosine_threshold:
            dropped += 1
            continue
        kept_indices.append(i)

    kept_records = [records[i] for i in kept_indices]
    return kept_records, dropped, round(max_cosine_seen, 4)


def run_dedup_and_filter_pipeline(
    records: list[dict[str, Any]],
    minhash_threshold: float = 0.85,
    minhash_num_perm: int = 128,
    semantic_cosine_threshold: float = 0.94,
) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    """Execute Stage A (Heuristic), Stage B (MinHash LSH), and Stage C (:11434 Semantic Embedding Dedup)."""
    input_count = len(records)

    stage_a_kept = [r for r in records if passes_heuristic_filter(r)]
    dropped_heuristic = input_count - len(stage_a_kept)

    stage_b_kept, dropped_minhash = deduplicate_minhash_lsh(
        stage_a_kept,
        threshold=minhash_threshold,
        num_perm=minhash_num_perm,
    )

    stage_c_kept, dropped_semantic, max_cos = deduplicate_semantic_embeddings(
        stage_b_kept,
        cosine_threshold=semantic_cosine_threshold,
    )

    stats = {
        "input_count": input_count,
        "after_heuristic": len(stage_a_kept),
        "dropped_heuristic": dropped_heuristic,
        "after_minhash_lsh": len(stage_b_kept),
        "dropped_minhash_lsh": dropped_minhash,
        "after_semantic_embed": len(stage_c_kept),
        "dropped_semantic_embed": dropped_semantic,
        "max_cosine_similarity_observed": max_cos,
        "minhash_threshold": minhash_threshold,
        "minhash_num_perm": minhash_num_perm,
        "semantic_cosine_threshold": semantic_cosine_threshold,
    }
    return stage_c_kept, stats
